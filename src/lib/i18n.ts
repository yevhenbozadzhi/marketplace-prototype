export type TranslationKey = keyof typeof translations.en;

export function isLocale(value: string): value is Locale {
  return locales.includes(value as Locale);
}

export function translate(locale: Locale, key: TranslationKey) {
  return translations[locale][key] ?? translations.en[key];
}

export function translateRole(locale: Locale, role: "buyer" | "seller" | "manager") {
  return translate(locale, role);
}

export function translateStatus(locale: Locale, status: string) {
  if (status === "draft") return translate(locale, "statusDraft");
  if (status === "published") return translate(locale, "statusPublished");
  if (status === "suspended") return translate(locale, "statusSuspended");
  if (status === "removed") return translate(locale, "statusRemoved");
  if (status === "active") return translate(locale, "active");
  return status;
}
